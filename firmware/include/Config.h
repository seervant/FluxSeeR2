// --- Вспомогательное ---
// Аналог Arduino map(), но для чисел с плавающей точкой.
// В ядре ESP32 map() реализован только для long, поэтому float молча
// округляется до целого — использовать его с дробными величинами нельзя.
static inline float mapf(float x, float in_min, float in_max, float out_min, float out_max) {
  if (in_max == in_min) return out_min;
  return (x - in_min) * (out_max - out_min) / (in_max - in_min) + out_min;
}

