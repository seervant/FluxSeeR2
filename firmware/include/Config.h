// ============================================================================
// ПИТАНИЕ
//
//  Аккумулятор: 4 x LiitoKala Lii-70S 26650 (4S1P), ~14.8 В номинал, 28 А·ч
//  BMS: 4S 40 А (Balance)
//  Преобразователь: TZT teng 300Вт 20А, понижающий 4S -> 5 В, КПД ~96 %
//
//  Бюджет тока:
//    949 LED x 60 мА = 56.9 А в худшем случае (белый на полную)
//    Ночник, а не прожектор: ограничиваем 8 А -> 40 Вт на светодиоды
//    Порог защиты преобразователя (CC) выставляется на 10 А
//    Ток из пакета: 8 А / 0.96 = 8.4 А при 14.8 В -> BMS 40 А с запасом
// ============================================================================
#define BAT_CELLS            4
#define BAT_CELL_FULL_V      4.20f
#define BAT_CELL_EMPTY_V     3.00f
#define BAT_PACK_FULL_V      (BAT_CELLS * BAT_CELL_FULL_V)    // 16.80 В
#define BAT_PACK_EMPTY_V     (BAT_CELLS * BAT_CELL_EMPTY_V)   // 12.00 В

// Делитель напряжения на входе MAX17043: 4 равных резистора (3 x 10 кОм + 10 кОм).
// На полном заряде 16.8 В / 4 = 4.2 В — в пределах диапазона чипа (0..5.5 В).
#define BAT_DIVIDER_RATIO    4.0f

// Ток одного канала WS2812B при полной яркости канала, мА
