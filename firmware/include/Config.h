// ============================================================================
// ПИТАНИЕ
//
//  Аккумулятор: 4 x 26650 (4S1P), ~14.8 В номинал, 20 А·ч
//  BMS: 4S 40 А (Balance)
//  Преобразователь: TZT teng 300Вт 20А, понижающий 4S -> 5 В, КПД ~90 %
//
//  Бюджет тока:
//    949 LED x 60 мА = 56.9 А в худшем случае (белый на полную)
//    Преобразователь даёт 20 А -> 100 Вт на светодиоды
//    Из них ~1 А уходит на ESP32 и периферию
//    => на светодиоды остаётся 18 А, они ограничиваются программно
