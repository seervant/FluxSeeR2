#pragma once
#include <Arduino.h>
#include "Types.h"

// ============================================================================
// МАСТЕР КАЛИБРОВКИ 3D-СЦЕНЫ
//
// Задача калибровки — связать три вещи, которые иначе никак не связаны:
//   1) физическую раскладку светодиодов (номера столбцов),
//   2) систему координат датчика MPU-6050,
//   3) направление на наблюдателя.
//
// Шаги (каждый подтверждается нажатием кнопки энкодера):
//
//   Шаг 1 «ПРИЦЕЛ»
//     Лампа стоит вертикально, экраном к пользователю. Пользователь
//     поворачивает её так, чтобы нарисованный прицел смотрел в глаза,
//     и подтверждает. Так определяется направление на наблюдателя
//     в системе корпуса и фиксируется опорная поза.
//
//   Шаг 2 «ВПРАВО»
//     Лампа наклоняется на 90° вправо (верх лампы — вправо).
//     Подтверждение. По вектору гравитации определяется ось X корпуса.
//
//   Шаг 3 «НАЗАД»
//     Лампа наклоняется на 90° назад (верх лампы — от себя, пользователь
//     смотрит сверху). Подтверждение. Проверяется ось Z корпуса.
//
// После шага 3 матрица перехода «MPU -> корпус» сохраняется в NVS,
// и с этого момента эффекты 3D-сцены работают с привязкой к гравитации
// и к корпусу.
// ============================================================================

#define CALIB3D_STEP_IDLE   0
#define CALIB3D_STEP_AIM    1
#define CALIB3D_STEP_RIGHT  2
#define CALIB3D_STEP_BACK   3
#define CALIB3D_STEP_DONE   4

// Запустить мастер калибровки
void calib3dStart();

// Прервать мастер (без сохранения)
void calib3dCancel();

// Активен ли мастер
bool calib3dActive();

// Текущий шаг (CALIB3D_STEP_*)
uint8_t calib3dStep();

// Обработка подтверждения (нажатие кнопки энкодера)
void calib3dTick();

// Отрисовка прицела и указателей на светодиоды
void calib3dRender();

// Вывод инструкций на OLED
void calib3dDisplay();
