#pragma once
#include <Arduino.h>
#include <FastLED.h>
#include "Math3D.h"

// ============================================================================
// РЕНДЕР 3D-СЦЕНЫ НА ЦИЛИНДРИЧЕСКОЙ МАТРИЦЕ
//
// Принцип: для каждого пикселя матрицы строится луч «глаз -> точка поверхности
// цилиндра» и ищется пересечение с объёмной фигурой. Видны только те
// столбцы, чья внешняя нормаль смотрит на глаз, поэтому на экране
// отображается ровно та часть объекта, которую видит наблюдатель.
//
// Формы задаются набором полупространств (выпуклые многогранники):
//   куб     — 6 плоскостей
//   октаэдр — 8 плоскостей
//   призма  — 8 плоскостей (шестигранная колонна)
//   сфера   — аналитическое пересечение луча со sphere
//
// Рёбра подсвечиваются по расстоянию от точки попадания до ближайшего
// ребра грани, затенение граней — по косинусу угла между нормалью и
// направлением на глаз, глубина — по удалённости от глаза.
// ============================================================================

// Количество фигур, переключаемых параметром FIGURE
#define SCENE_FIGURE_COUNT 4

// Индексы фигур
#define SCENE_FIG_CUBE    0
#define SCENE_FIG_OCTA    1
#define SCENE_FIG_PRISM   2
#define SCENE_FIG_SPHERE  3

// Индексы параметров эффектов 3D-сцены (одинаковые для эффектов 8 и 9)
#define SCENE_P_BRIGHT 0
#define SCENE_P_FIGURE 1
#define SCENE_P_SIZE   2
#define SCENE_P_COLOR  3
#define SCENE_P_EDGE   4
#define SCENE_P_DIST   5
#define SCENE_P_EYEH   6
#define SCENE_PARAM_COUNT 7

// Параметры отрисовки сцены
struct SceneOptions {
  uint8_t figure  = SCENE_FIG_CUBE;   // тип фигуры
  float   sizePct = 55.0f;             // размер объекта, % от радиуса корпуса
  uint8_t hue     = 0;                 // базовый оттенок (0..255)
  float   edgeMm  = 8.0f;              // ширина подсветки рёбер, мм
};

// Отрисовка сцены на боковую матрицу.
//
//   bodyToScene — поворот из системы корпуса в систему сцены (кватернион)
//   eyeScene    — положение наблюдателя в системе сцены, мм
//
// Система сцены: X — влево от зрителя, Y — вверх, Z — наружу столбца 0.
// Начало координат — центр лампы.
void scene3dRender(const SceneOptions& opt, const Quat& bodyToScene, const Vec3& eyeScene);
