#pragma once
#include <Arduino.h>
#include "Math3D.h"

// ============================================================================
// ОРИЕНТАЦИЯ ЛАМПЫ
//
// Отслеживает поворот корпуса относительно калибровочной (мировой) позы
// и обеспечивает эффекты 3D-сцены:
//
//   1) «Сцена, привязанная к гравитации» — объект зафиксирован в мире.
//      Вертикаль всегда по гравитации, поворот лампы не вращает сцену.
//
//   2) «Сцена, привязанная к корпусу» — объект жёстко связан с лампой
//      и вращается вместе с ней.
//
// Основные понятия
// -----------------
//  Система корпуса (body): X — влево от зрителя (ось, вокруг которой
//  лампа наклоняется вправо), Y — вверх, Z — наружу столбца 0.
//  Обе оси X и Y задаются калибровкой по гравитации, Z = X x Y.
//
//  Калибровочная (мировая) система (cal): совпадает с системой корпуса
//  в момент калибровки. Ось Y — вверх, ось Z — направление на зрителя
//  в момент калибровки.
//
//  psi — кватернион перехода корпус -> калибровочная система:
//         v_cal = psi * v_body * psi^(-1)
//
//  Матрица калибровки хранит оси корпуса в координатах MPU-6050, что
//  позволяет переводить показания датчика (ускорение, гироскоп) в
//  систему корпуса.
//
// Дрейф: рыскание (поворот вокруг вертикали) акселерометром не
// определяется, поэтому накапливается ошибка интегрирования гироскопа.
// Ошибка наклона корректируется постоянно по вектору гравитации.
// ============================================================================

// --- Калибровка (сохраняется в NVS) ---
extern Mat3 g_bodyAxesInMpu;   // столбцы — оси корпуса в координатах MPU
extern bool g_sceneCalibrated; // калибровка выполнена и загружена

// Загрузка калибровки из NVS (вызывается один раз при старте)
void orientationInit();

// Шаг интегрирования: гироскоп + коррекция по гравитации
void orientationTick(uint32_t dtMs);

// Относительная ориентация корпуса (тело -> калибровочная система)
const Quat& orientationRel();

// Сброс относительной ориентации (после калибровки — новая опорная поза)
void orientationResetRel();

// Задать относительную ориентацию явно (используется мастером калибровки)
void orientationSetRel(const Quat& q);

// Применить и сохранить новую калибровку (оси корпуса в координатах MPU)
void orientationSetCalibration(const Mat3& bodyAxesInMpu);

// Вспомогательное: перевод вектора из системы MPU в систему корпуса
Vec3 mpuToBody(const Vec3& v);

// Вспомогательное: перевод вектора из системы корпуса в систему MPU
Vec3 bodyToMpu(const Vec3& v);
