#pragma once
#include <Arduino.h>
#include "Config.h"

// ============================================================================
// ДИСПЛЕЙ: 0.96" I2C OLED 128x64 (gm009605v4, SSD1306/SSD1315)
//
// Содержимое по ТЗ (раздел 4):
//   - версия прошивки
//   - общее количество эффектов / номер текущего эффекта / название
//   - общее количество параметров / номер текущего параметра / название и значение
//   - напряжение и заряд аккумулятора
