// Инициализация дисплея. НЕ блокирует: при отсутствии экрана работа продолжается.
void displayInit();

// Периодическое обновление (не чаще, чем раз в intervalMs)
void displayTick(uint32_t intervalMs);

// Немедленная перерисовка
void displayRefresh();

// Вывод служебного экрана (режим проверки раскладки)
void displayService(const char* line1, const char* line2);

// Готовность дисплея (false — экран не инициализирован)
bool displayReady();