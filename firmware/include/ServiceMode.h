#pragma once
#include <Arduino.h>
#include "Types.h"

// ============================================================================
// РЕЖИМ ПРОВЕРКИ РАСКЛАДКИ (сервисный)
//
// Нужен, чтобы после сборки определить правильные значения FLIP_X / FLIP_Y
// (боковая матрица) и DISK_RING_REVERSED / DISK_SEG_REVERSED (верхний диск)
// без пересборки и перепрошивки прошивки.
//
// ВХОД:  удерживать кнопку энкодера при включении питания,
//        либо удерживать её 2 секунды в обычном режиме
// ЭКРАНЫ (сенсоры: левая TTP223 — назад, правая — вперёд):
//   0  SIDE COL  — горит весь столбец боковой матрицы (0..47)
//   1  SIDE ROW  — горит вся строка боковой матрицы (0..15), по «змейке»
//   2  DISK RING — горит целиком кольцо верхнего диска (0 — центр)
//   3  DISK SEG  — горит один сегмент выбранного кольца
// Значение меняется энкодером.
// ВЫХОД: удерживать кнопку энкодера 2 секунды
// ============================================================================

#define SERVICE_SCREEN_COUNT 4

// Проверка входа при включении (кнопка энкодера зажата)
void serviceInit();

// Активен ли сервисный режим
bool serviceActive();

// Включить/выключить сервисный режим
void serviceToggle();

// Обработка ввода: дельта энкодера + состояние сенсоров
void serviceTick(int32_t encDelta);

// Отрисовка тестового паттерна на светодиоды
void serviceRender();

// Вывод информации на OLED
void serviceDisplay();