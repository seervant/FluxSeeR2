// ---------------------------------------------------------------------------
// Эффекты (порядок фиксирован ТЗ, раздел 5)
// ---------------------------------------------------------------------------
enum EffectId : uint8_t {
  EFFECT_STATIC = 0,        // 1. Статический
  EFFECT_RAINBOW_Z,         // 2. Динамическая Z-радуга
  EFFECT_RAINBOW_CIRCLE,    // 3. Динамическая круговая радуга
  EFFECT_FLUID,             // 4. Жидкость
  EFFECT_SPIRAL,            // 5. Спираль
  EFFECT_BALLS,             // 6. Мячи в вакууме
  EFFECT_LAVA,              // 7. Лавовая лампа
  EFFECT_SCENE_GRAV,        // 8. 3D-сцена, привязанная к гравитации
  EFFECT_SCENE_BODY,        // 9. 3D-сцена, привязанная к корпусу
  EFFECT_COUNT
};

// ---------------------------------------------------------------------------
// Типы параметров: определяют шкалу отображения и нормировку значения
// ---------------------------------------------------------------------------
enum ParamKind : uint8_t {
  PK_BRIGHTNESS = 0,  // 1..16   -> яркость 16..255
  PK_COLOR,           // 1..64   -> оттенок (Hue) 0..255
  PK_SPEED,           // -32..+32, знак задаёт направление
  PK_SCALE,           // числовой без нормировки (масштаб, вязкость, скорость)
  PK_ANGLE,           // градусы
  PK_PERCENT,         // 1..100 %
  PK_G_POWER,         // индекс в экспоненциальной шкале % силы G
  PK_COUNT,           // количество объектов
  PK_SIZE,            // размер в пикселях
  PK_MODE,            // 0..1 (Авто / Ручной)
  PK_FIGURE,          // 0..4 (Куб / Октаэдр / Призма / Сфера / Модель)
  PK_MODEL            // номер модели в списке файлов SD-карты
};

// Флаги параметра
#define PF_WRAP  0x01   // циклическая прокрутка по краям диапазона

// ---------------------------------------------------------------------------
// Описание одного параметра эффекта
// ---------------------------------------------------------------------------
struct ParamSpec {
  const char* name;   // ASCII-подпись для OLED (до 10 символов)
  int16_t     min;
  int16_t     max;
  uint8_t     kind;   // ParamKind
  uint8_t     flags;  // PF_WRAP и т.п.
};

// Максимальное число параметров у одного эффекта
#define MAX_PARAMS 14

// ---------------------------------------------------------------------------
// Телеметрия
// ---------------------------------------------------------------------------
struct Telemetry {
  // Акселерометр (нормализованный вектор ускорения)
  float    accX = 0.0f;
  float    accY = 0.0f;
  float    accZ = -1.0f;

  // Гироскоп (угловая скорость, рад/с в системе датчика)
  float    gyroX = 0.0f;
  float    gyroY = 0.0f;
  float    gyroZ = 0.0f;
  bool     gyroReady = false;   // гироскоп отвечает и откалиброван

  // Батарея
  uint8_t  battery        = 50;      // процент заряда, 0..100
  float    smoothBattery  = 50.0f;   // сглаженный процент (для анимации)
  float    voltage        = 12.60f;  // напряжение пакета, В
  float    prevVoltage    = 12.60f;
  bool     batteryConnected = true;
  bool     isCharging     = false;
  bool     criticalLow    = false;
  bool     i2cErrorMAX    = false;
  bool     maxResetTriggered = false;

  // Звук
  uint16_t micValue       = 0;       // сырое значение АЦП микрофона
  uint16_t spectrumValue  = 0;       // сырое значение АЦП анализатора спектра

  // Ориентация
  bool     gravityCalibrated = false;
  bool     isShaken          = false;   // флаг резкого встряхивания
};

// ---------------------------------------------------------------------------
// Вспомогательная 3D-структура для физики жидкости
// ---------------------------------------------------------------------------
struct Vector3D {
  float x = 0.0f, y = 0.0f, z = 0.0f;
  Vector3D() = default;
  Vector3D(float _x, float _y, float _z) : x(_x), y(_y), z(_z) {}
};

// ---------------------------------------------------------------------------
// Модель «пружина-затухание» для вектора гравитации (эффект «Жидкость»)
// ---------------------------------------------------------------------------
struct LiquidPhysics3D {
  Vector3D currentG = Vector3D(0.0f, 0.0f, -1.0f);
  Vector3D velG     = Vector3D(0.0f, 0.0f, 0.0f);
  float    stiffness = 0.18f;   // отклик (жёсткость пружины)
  float    damping   = 0.88f;   // вязкость (затухание)
};

// ---------------------------------------------------------------------------
// Частица (пузырёк) для эффекта «Жидкость»
// ---------------------------------------------------------------------------
struct Bubble {
  float    x = 0.0f;          // координата X (столбец)
  float    y = 0.0f;          // координата Y (строка)
  float    speedMult = 1.0f;  // индивидуальный множитель скорости
  uint8_t  hueOffset = 0;     // индивидуальное смещение оттенка
  uint8_t  size = 1;          // индивидуальный радиус, в пикселях
  bool     active = false;
};
